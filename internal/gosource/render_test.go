func TestRenderRetainsCommentsAndIsolatesEdits(t *testing.T) {
	source := []byte("//go:build e2e\n\n// Code generated by fixture. DO NOT EDIT.\npackage p\n\nimport _ \"example.com/plugin\"\n\n// Message is displayed.\nconst Message = \"old\"\n\ntype Form struct { Label string `json:\"label\"` }\n")
	for _, value := range []string{"", "café\n東京", "a\"b\\c"} {
		t.Run(strconv.Quote(value), func(t *testing.T) {
			t.Parallel()
			got, err := Render("page.go", source, func(_ *token.FileSet, file *ast.File) error {
				declaration, ok := file.Decls[1].(*ast.GenDecl)
				if !ok || len(declaration.Specs) == 0 {
					return errors.New("fixture has no constant declaration")
				}
				valueSpec, ok := declaration.Specs[0].(*ast.ValueSpec)
				if !ok {
					return errors.New("fixture declaration is not a value")
				}
				valueSpec.Values[0] = &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(value)}
				return nil
			})
			require.NoError(t, err)
			want, err := format.Source([]byte(strings.Replace(string(source), `"old"`, strconv.Quote(value), 1)))
			require.NoError(t, err)
			assert.Equal(t, string(want), string(got), "render differs from gofmt")

			again, err := Render("page.go", got, nil)
			require.NoError(t, err)
			assert.Equal(t, string(got), string(again), "second render differs")
		})
	}
}

func TestRenderReportsFilenameAndPhase(t *testing.T) {
	const name = "broken.go"

	output, err := Render(name, []byte("package ?"), nil)
	assert.Nil(t, output)
	require.Error(t, err)
	assert.Contains(t, err.Error(), name, "parse failure names the file")

	missing := errors.New("missing Example")
	output, err = Render(name, []byte("package fixture"), func(*token.FileSet, *ast.File) error { return missing })
	assert.Nil(t, output)
	require.ErrorIs(t, err, missing)
	assert.Contains(t, err.Error(), name, "edit failure names the file")

	output, err = Render(name, []byte("package fixture"), func(_ *token.FileSet, file *ast.File) error {
		file.Name.Name = "123"
		return nil
	})
	assert.Nil(t, output)
	require.Error(t, err)
	assert.Contains(t, err.Error(), name, "invalid output names the file")
}

func TestReplaceModuleImports(t *testing.T) {
	const source = "package fixture\nimport (_ \"example.org/p\"; child \"example.org/p/child\"; _ \"example.org/p-old\")\n"
	var edited int
	got, err := Render("imports.go", []byte(source), func(_ *token.FileSet, file *ast.File) error {
		var replaceErr error
		edited, replaceErr = ReplaceModuleImports(file, "example.org/p", "example.com/renamed/v2")
		return replaceErr
	})
	require.NoError(t, err)
	assert.Equal(t, 2, edited)
	for _, want := range []string{`_ "example.com/renamed/v2"`, `child "example.com/renamed/v2/child"`, `_ "example.org/p-old"`} {
		assert.Contains(t, string(got), want)
	}
}

func TestReplaceModuleImportsReportsInvalidPath(t *testing.T) {
	file := &ast.File{Imports: []*ast.ImportSpec{{Path: &ast.BasicLit{Kind: token.STRING, Value: `"unterminated`}}}}

	count, err := ReplaceModuleImports(file, "example.org/p", "example.com/q")

	require.ErrorContains(t, err, "unterminated")
	assert.Zero(t, count)
}

func TestRenderFixture(t *testing.T) {
	const source = "package fixture\n\nimport _ \"example.org/p/dist\"\n"
	tests := []struct {
		name       string
		source     string
		wantErr    string
		wantImport string
	}{
		{name: "one import", source: source, wantImport: `_ "example.com/app/v2/dist"`},
		{name: "no import", source: "package fixture\n", wantErr: "found 0"},
		{name: "two imports", source: "package fixture\n\nimport (\n\t_ \"example.org/p/a\"\n\t_ \"example.org/p/b\"\n)\n", wantErr: "found 2"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			got, err := RenderFixture("fixture.go", []byte(test.source), "example.org/p", "example.com/app/v2")
			if test.wantErr != "" {
				require.ErrorContains(t, err, test.wantErr)
				assert.Nil(t, got)
				return
			}
			require.NoError(t, err)
			assert.Contains(t, string(got), test.wantImport)
			assert.NotContains(t, string(got), "example.org/p")
		})
	}
}

