package generated_writer

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"io/fs"

	"piko.sh/piko/internal/sqldb/sqldb_dto"
	"piko.sh/safedisk"
)

const (
	// GeneratedFileHeader is the first line of every file Piko generates for SQL access,
	// followed by a blank line.
	GeneratedFileHeader = "// Code generated by Piko. DO NOT EDIT.\n\n"
)

// OutputDirectory is the part of a sandbox the writer needs.
type OutputDirectory interface {
	// ReadDir lists the entries of the directory named name.
	//
	// Takes name (string) which is the directory path to list.
	//
	// Returns []fs.DirEntry which holds the directory entries.
	// Returns error when the directory cannot be read.
	ReadDir(name string) ([]fs.DirEntry, error)

	// Open opens the file named name for reading.
	//
	// Takes name (string) which is the path of the file to open.
	//
	// Returns safedisk.FileHandle which is the open file, and which the caller must close.
	// Returns error when the file cannot be opened.
	Open(name string) (safedisk.FileHandle, error)

	// Remove deletes the file named name.
	//
	// Takes name (string) which is the path of the file to delete.
	//
	// Returns error when the file cannot be deleted.
	Remove(name string) error

	// WriteFile writes data to the file named name, creating or truncating it.
	//
	// Takes name (string) which is the path of the file to write.
	// Takes data ([]byte) which is the content to write.
	// Takes perm (fs.FileMode) which sets the permissions of a new file.
	//
	// Returns error when the file cannot be written.
	WriteFile(name string, data []byte, perm fs.FileMode) error
}

// WriteFiles prunes stale generated files from directory and writes files into it.
//
// Files with empty content are skipped. A file is pruned when it is not among files and
// starts with GeneratedFileHeader or one of legacyHeaders.
//
// Takes directory (OutputDirectory) which is the sandboxed output directory.
// Takes files ([]sqldb_dto.GeneratedFile) which holds the generated files.
// Takes permissions (fs.FileMode) which sets the mode of written files.
// Takes legacyHeaders ([]string) which lists earlier generated-code headers that also
// mark a file as safe to prune.
//
// Returns error when listing, pruning or writing fails.
func WriteFiles(directory OutputDirectory, files []sqldb_dto.GeneratedFile, permissions fs.FileMode, legacyHeaders ...string) error {
	if err := pruneStale(directory, fileNameSet(files), generatedHeaders(legacyHeaders)); err != nil {
		return err
	}

	for _, file := range files {
		if len(file.Content) == 0 {
			continue
		}
		if err := directory.WriteFile(file.Name, file.Content, permissions); err != nil {
			return fmt.Errorf("writing generated file %q: %w", file.Name, err)
		}
	}
	return nil
}

// CountQueryMethods counts the query methods in generated files.
//
// Takes files ([]sqldb_dto.GeneratedFile) which holds the generated files.
//
// Returns int which is the number of methods on the generated Queries type found in files
// whose names end in .sql.go.
func CountQueryMethods(files []sqldb_dto.GeneratedFile) int {
	count := 0
	for _, file := range files {
		if !bytes.HasSuffix([]byte(file.Name), []byte(".sql.go")) {
			continue
		}
		count += bytes.Count(file.Content, []byte("func (queries *Queries)"))
	}
	return count
}

// generatedHeaders returns the current header followed by the legacy ones.
//
// Takes legacyHeaders ([]string) which lists earlier headers.
//
// Returns [][]byte which holds every header that marks a generated file.
func generatedHeaders(legacyHeaders []string) [][]byte {
	headers := make([][]byte, 0, len(legacyHeaders)+1)
	headers = append(headers, []byte(GeneratedFileHeader))
	for _, header := range legacyHeaders {
		headers = append(headers, []byte(header))
	}
	return headers
}

// fileNameSet collects the names of the files that will be written.
//
// Takes files ([]sqldb_dto.GeneratedFile) which holds the generated files.
//
// Returns map[string]struct{} which holds every name with non-empty content.
func fileNameSet(files []sqldb_dto.GeneratedFile) map[string]struct{} {
	names := make(map[string]struct{}, len(files))
	for _, file := range files {
		if len(file.Content) == 0 {
			continue
		}
		names[file.Name] = struct{}{}
	}
	return names
}

// pruneStale removes generated files that are no longer produced.
//
// Takes directory (OutputDirectory) which is the output directory.
// Takes keep (map[string]struct{}) which holds the names being written.
// Takes headers ([][]byte) which mark a file as generated.
//
// Returns error when the directory cannot be listed or a file cannot be removed.
func pruneStale(directory OutputDirectory, keep map[string]struct{}, headers [][]byte) error {
	entries, err := directory.ReadDir(".")
	if err != nil {
		return fmt.Errorf("listing output directory: %w", err)
	}

	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if _, wanted := keep[name]; wanted {
			continue
		}

		generated, inspectErr := hasGeneratedHeader(directory, name, headers)
		if inspectErr != nil {
			return fmt.Errorf("inspecting candidate stale file %q: %w", name, inspectErr)
		}
		if !generated {
			continue
		}

		if removeErr := directory.Remove(name); removeErr != nil && !errors.Is(removeErr, fs.ErrNotExist) {
			return fmt.Errorf("removing stale generated file %q: %w", name, removeErr)
		}
	}
	return nil
}

// hasGeneratedHeader reports whether the named file starts with one of headers.
//
// Takes directory (OutputDirectory) which holds the file.
// Takes name (string) which is the file to inspect.
// Takes headers ([][]byte) which mark a file as generated.
//
// Returns bool which is true when the file starts with a generated header.
// Returns error when the file cannot be read.
func hasGeneratedHeader(directory OutputDirectory, name string, headers [][]byte) (bool, error) {
	handle, openErr := directory.Open(name)
	if openErr != nil {
		if errors.Is(openErr, fs.ErrNotExist) {
			return false, nil
		}
		return false, openErr
	}
	defer func() { _ = handle.Close() }()

	longest := 0
	for _, header := range headers {
		longest = max(longest, len(header))
	}

	prefix := make([]byte, longest)
	read, readErr := io.ReadFull(handle, prefix)
	if readErr != nil && !errors.Is(readErr, io.EOF) && !errors.Is(readErr, io.ErrUnexpectedEOF) {
		return false, readErr
	}

	for _, header := range headers {
		if bytes.HasPrefix(prefix[:read], header) {
			return true, nil
		}
	}
	return false, nil
}
