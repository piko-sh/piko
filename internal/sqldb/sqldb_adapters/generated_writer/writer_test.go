package generated_writer

import (
	"testing"

	"github.com/stretchr/testify/require"

	"piko.sh/piko/internal/sqldb/sqldb_dto"
	"piko.sh/safedisk"
)

func newOutput(t *testing.T) safedisk.Sandbox {
	t.Helper()
	sandbox, err := safedisk.NewSandbox(t.TempDir(), safedisk.ModeReadWrite)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, sandbox.Close()) })
	return sandbox
}

func TestWriteFilesWritesNonEmptyFiles(t *testing.T) {
	t.Parallel()

	output := newOutput(t)
	files := []sqldb_dto.GeneratedFile{
		{Name: "models.go", Content: []byte(GeneratedFileHeader + "package db\n")},
		{Name: "empty.go", Content: nil},
	}

	require.NoError(t, WriteFiles(output, files, 0o644))

	data, err := output.ReadFile("models.go")
	require.NoError(t, err)
	require.Equal(t, GeneratedFileHeader+"package db\n", string(data))
	_, err = output.ReadFile("empty.go")
	require.Error(t, err)
}

func TestWriteFilesPrunesOnlyGeneratedFiles(t *testing.T) {
	t.Parallel()

	output := newOutput(t)
	require.NoError(t, output.WriteFile("stale.sql.go", []byte(GeneratedFileHeader+"package db\n"), 0o644))
	require.NoError(t, output.WriteFile("legacy.sql.go", []byte("// Code generated by sgl. DO NOT EDIT.\n\npackage db\n"), 0o644))
	require.NoError(t, output.WriteFile("handwritten.go", []byte("package db\n"), 0o644))
	require.NoError(t, output.WriteFile("short.go", []byte("pa"), 0o644))

	files := []sqldb_dto.GeneratedFile{{Name: "models.go", Content: []byte(GeneratedFileHeader + "package db\n")}}
	require.NoError(t, WriteFiles(output, files, 0o644, "// Code generated by sgl. DO NOT EDIT.\n\n"))

	_, err := output.ReadFile("stale.sql.go")
	require.Error(t, err)
	_, err = output.ReadFile("legacy.sql.go")
	require.Error(t, err)
	_, err = output.ReadFile("handwritten.go")
	require.NoError(t, err)
	_, err = output.ReadFile("short.go")
	require.NoError(t, err)
}

func TestCountQueryMethods(t *testing.T) {
	t.Parallel()

	files := []sqldb_dto.GeneratedFile{
		{Name: "users.sql.go", Content: []byte("func (queries *Queries) A() {}\nfunc (queries *Queries) B() {}\n")},
		{Name: "querier.go", Content: []byte("func (queries *Queries) WithTx() {}\n")},
	}

	require.Equal(t, 2, CountQueryMethods(files))
}
