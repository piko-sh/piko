// registration pairs a dispatch key with its handler function name.
type registration struct {
	// key is the dispatch constant identifier from the source maps.
	key string

	// handler is the handler function identifier from the source maps.
	handler string
}

// main parses the four registration maps and writes the dispatch switch.
func main() {
	files := []string{
		"vm_handler_table.go",
		"vm_handler_flat_table.go",
	}

	want := map[string]*[]registration{
		"handlerRegistrations":   {},
		"flatTier1Registrations": {},
		"flatTier2Registrations": {},
		"flatTier3Registrations": {},
	}

	for name := range want {
		list := make([]registration, 0, 256)
		want[name] = &list
	}

	for _, path := range files {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			fmt.Fprintf(os.Stderr, "parse %s: %v\n", path, err)
			os.Exit(1)
		}
		collectRegistrations(f, want)
	}

	for name, list := range want {
		sort.Slice(*list, func(i, j int) bool { return (*list)[i].key < (*list)[j].key })
		fmt.Fprintf(os.Stderr, "// %s: %d entries\n", name, len(*list))
	}

	file := buildFile(want)

	var body bytes.Buffer
	if err := format.Node(&body, token.NewFileSet(), file); err != nil {
		fmt.Fprintf(os.Stderr, "format: %v\n", err)
		os.Exit(1)
	}

	header := []byte(generatedFileHeader)
	rawOutput := append(header, body.Bytes()...)
	output, err := format.Source(rawOutput)
	if err != nil {
		fmt.Fprintf(os.Stderr, "format.Source: %v\n", err)
		os.Exit(1)
	}

	const outputPath = "vm_handler_flat_switch.go"
	if err := os.WriteFile(outputPath, output, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", outputPath, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "// wrote %s (%d bytes)\n", outputPath, len(output))
}

// collectRegistrations records map-literal entries from a source file.
//
// Walks the AST and captures every entry from the four registration vars of interest.
// Entries that are not bare identifier keys mapped to bare identifier values are skipped
// silently; the source files only use that shape today.
//
// Takes file (*ast.File) which is the parsed source file.
// Takes want (map[string]*[]registration) which buckets entries by the source map
// variable name.
func collectRegistrations(file *ast.File, want map[string]*[]registration) {
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.VAR {
			continue
		}
		for _, spec := range genDecl.Specs {
			valueSpec, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			if len(valueSpec.Names) != 1 || len(valueSpec.Values) != 1 {
				continue
			}
			name := valueSpec.Names[0].Name
			list, ok := want[name]
			if !ok {
				continue
			}
			lit, ok := valueSpec.Values[0].(*ast.CompositeLit)
			if !ok {
				continue
			}
			for _, elt := range lit.Elts {
				kv, ok := elt.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				keyIdent, kok := kv.Key.(*ast.Ident)
				if !kok {
					continue
				}
				valIdent, vok := kv.Value.(*ast.Ident)
				if !vok {
					continue
				}
				*list = append(*list, registration{key: keyIdent.Name, handler: valIdent.Name})
			}
		}
	}
}

// buildFile assembles the ast.File holding flatDispatchSwitch.
//
// Every identifier (handler name, sub-op constant, parameter) is a real *ast.Ident so
// Go's formatter prints them verbatim; nothing is constructed by string concatenation.
//
// Takes want (map[string]*[]registration) which carries the four collected registration
// lists keyed by source map name.
//
// Returns *ast.File which is the generated dispatcher file AST.
func buildFile(want map[string]*[]registration) *ast.File {
	tier0 := *want["handlerRegistrations"]
	tier1 := *want["flatTier1Registrations"]
	tier2 := *want["flatTier2Registrations"]
	tier3 := *want["flatTier3Registrations"]

	cases := make([]ast.Stmt, 0, len(tier0)+len(tier1)+len(tier2)+len(tier3))
	cases = appendTierCases(cases, tier0, "")
	cases = appendTierCases(cases, tier1, "flatHandlerTier1Base")
	cases = appendTierCases(cases, tier2, "flatHandlerTier2Base")
	cases = appendTierCases(cases, tier3, "flatHandlerTier3Base")

	primarySwitch := &ast.SwitchStmt{
		Tag:  callDispatchIndex(),
		Body: &ast.BlockStmt{List: cases},
	}

	defaultSwitch := buildDefaultSwitch()

	funcDecl := &ast.FuncDecl{
		Doc:  funcDoc(),
		Name: ast.NewIdent("flatDispatchSwitch"),
		Type: dispatchFuncType(),
		Body: &ast.BlockStmt{List: []ast.Stmt{primarySwitch, defaultSwitch}},
	}

	return &ast.File{
		Name:  ast.NewIdent("interp_domain"),
		Decls: []ast.Decl{funcDecl},
	}
}

// appendTierCases emits one ast.CaseClause per entry.
//
// When prefix is empty the case label is `uint(KEY)`; otherwise it is `prefix +
// uint(KEY)`, matching the tier-1/2/3 region offsets.
//
// Takes stmts ([]ast.Stmt) which is the case-clause accumulator.
// Takes entries ([]registration) which are the registration entries.
// Takes prefix (string) which is the optional tier-base prefix.
//
// Returns []ast.Stmt which is the accumulator extended with the per-entry case clauses.
func appendTierCases(stmts []ast.Stmt, entries []registration, prefix string) []ast.Stmt {
	for _, entry := range entries {
		stmts = append(stmts, &ast.CaseClause{
			List: []ast.Expr{caseLabel(prefix, entry.key)},
			Body: []ast.Stmt{returnHandlerCall(entry.handler)},
		})
	}
	return stmts
}

// caseLabel builds the case-clause expression.
//
// For tier-0 entries (prefix==""), the result is `uint(KEY)`. For tier-1/2/3 entries, the
// result is `BASE + uint(KEY)`.
//
// Takes prefix (string) which is the optional tier-base prefix.
// Takes key (string) which is the dispatch key identifier.
//
// Returns ast.Expr which is the synthesised case label expression.
func caseLabel(prefix, key string) ast.Expr {
	uintCall := &ast.CallExpr{
		Fun:  ast.NewIdent("uint"),
		Args: []ast.Expr{ast.NewIdent(key)},
	}
	if prefix == "" {
		return uintCall
	}
	return &ast.BinaryExpr{
		X:  ast.NewIdent(prefix),
		Op: token.ADD,
		Y:  uintCall,
	}
}

// returnHandlerCall builds `return HANDLER(vm, frame, registers, instr)`.
//
// Takes handler (string) which is the handler function identifier.
//
// Returns *ast.ReturnStmt which is the synthesised return statement.
func returnHandlerCall(handler string) *ast.ReturnStmt {
	return &ast.ReturnStmt{
		Results: []ast.Expr{
			&ast.CallExpr{
				Fun: ast.NewIdent(handler),
				Args: []ast.Expr{
					ast.NewIdent("vm"),
					ast.NewIdent("frame"),
					ast.NewIdent("registers"),
					ast.NewIdent("instr"),
				},
			},
		},
	}
}

// callDispatchIndex builds `flatDispatchIndex(instr)`.
//
// Returns *ast.CallExpr which is the synthesised call expression.
func callDispatchIndex() *ast.CallExpr {
	return &ast.CallExpr{
		Fun:  ast.NewIdent("flatDispatchIndex"),
		Args: []ast.Expr{ast.NewIdent("instr")},
	}
}

// buildDefaultSwitch emits the tier-aware fallthrough switch.
//
// Runs when no primary case matched and routes through a range-bound switch on the flat
// index to the per-tier invalid-sub-op handler.
//
//	switch index := flatDispatchIndex(instr); {
//	case index < flatHandlerTier1Base:
//	    return handleInvalidOpcode(vm, frame, registers, instr)
//	case index < flatHandlerTier2Base:
//	    return handleFlatUnknownTier1(vm, frame, registers, instr)
//	case index < flatHandlerTier3Base:
//	    return handleFlatUnknownTier2(vm, frame, registers, instr)
//	default:
//	    return handleFlatUnknownTier3(vm, frame, registers, instr)
//	}
//
// Returns *ast.SwitchStmt which is the synthesised fallthrough switch.
func buildDefaultSwitch() *ast.SwitchStmt {
	indexIdent := ast.NewIdent("index")
	initStmt := &ast.AssignStmt{
		Lhs: []ast.Expr{indexIdent},
		Tok: token.DEFINE,
		Rhs: []ast.Expr{callDispatchIndex()},
	}

	rangeCase := func(boundary string, handler string) *ast.CaseClause {
		return &ast.CaseClause{
			List: []ast.Expr{
				&ast.BinaryExpr{
					X:  indexIdent,
					Op: token.LSS,
					Y:  ast.NewIdent(boundary),
				},
			},
			Body: []ast.Stmt{returnHandlerCall(handler)},
		}
	}
	defaultCase := &ast.CaseClause{
		List: nil,
		Body: []ast.Stmt{returnHandlerCall("handleFlatUnknownTier3")},
	}

	return &ast.SwitchStmt{
		Init: initStmt,
		Body: &ast.BlockStmt{
			List: []ast.Stmt{
				rangeCase("flatHandlerTier1Base", "handleInvalidOpcode"),
				rangeCase("flatHandlerTier2Base", "handleFlatUnknownTier1"),
				rangeCase("flatHandlerTier3Base", "handleFlatUnknownTier2"),
				defaultCase,
			},
		},
	}
}

// dispatchFuncType returns the func-type for flatDispatchSwitch.
//
// The synthesised signature is
//
//	func(vm *VM, frame *callFrame, registers *Registers, instr instruction) opResult.
//
// Returns *ast.FuncType which is the synthesised function type.
func dispatchFuncType() *ast.FuncType {
	param := func(name, typeName string, pointer bool) *ast.Field {
		var typeExpr ast.Expr = ast.NewIdent(typeName)
		if pointer {
			typeExpr = &ast.StarExpr{X: typeExpr}
		}
		return &ast.Field{
			Names: []*ast.Ident{ast.NewIdent(name)},
			Type:  typeExpr,
		}
	}
	return &ast.FuncType{
		Params: &ast.FieldList{List: []*ast.Field{
			param("vm", "VM", true),
			param("frame", "callFrame", true),
			param("registers", "Registers", true),
			param("instr", "instruction", false),
		}},
		Results: &ast.FieldList{List: []*ast.Field{
			{Type: ast.NewIdent("opResult")},
		}},
	}
}

// funcDoc returns the nolint directive that precedes the function.
//
// Architectural documentation lives next to the source-of-truth registration maps in
// vm_handler_flat_table.go, not in the emitted file - generated code should be minimal.
//
// The :all tag is the global form; without it gofmt treats "//nolint" as a non-directive
// comment and inserts a space ("// nolint"), which golangci-lint then ignores.
//
// Returns *ast.CommentGroup which holds the nolint directive comment.
func funcDoc() *ast.CommentGroup {
	return &ast.CommentGroup{List: []*ast.Comment{
		{Text: "//nolint:all // codegen-emitted dense dispatch switch"},
	}}
}

// quoteIdent quotes a registration key for diagnostic output.
//
// Wraps strconv.Quote so panics include a well-bounded string. Kept here so the
// generator's diagnostic surface is uniform; the emitter itself never builds identifiers
// through string ops.
//
// Takes name (string) which is the registration key to quote.
//
// Returns string which is the strconv.Quote of name.
//
//nolint:unused // diagnostic helper for future error paths
func quoteIdent(name string) string {
	return strconv.Quote(name)
}
