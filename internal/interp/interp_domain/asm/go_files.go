// GoFiles returns the list of asmgen-managed Go source files.
//
// Returns the asmgen.GoFile slice that cmd/asmgen passes alongside the HeaderFiles list.
func GoFiles() []asmgen.GoFile {
	return []asmgen.GoFile{
		{
			Name: "asm_call_trampolines_tier2_generated.go",
			Dir:  dispatchGoOutputDir,
			Emit: func(_ []asmgen.ArchitecturePort) string {
				return emitTier2TrampolineFile(Tier2HandlerShims())
			},
		},
	}
}

// emitTier2TrampolineFile returns the source text of the generated Go file containing one
// trampoline per tier-2 shim spec. The generated file lives in package interp_domain and
// references the tier2DispatchToHandler helper from asm_call_trampolines_tier2.go.
//
// Each trampoline is a one-liner that captures the specific handler at compile time, so
// the generated body, after Go's inliner processes tier2DispatchToHandler, compiles to a
// direct CALL of the matching handleXxx function (no indirect dispatch through
// handlerTable).
//
// Takes specs ([]Tier2HandlerShimSpec) which is the registered shim list, the same source
// of truth used to emit the .s shim files.
//
// Returns string which is the complete Go source text suitable for writing to
// asm_call_trampolines_tier2_generated.go.
func emitTier2TrampolineFile(specs []Tier2HandlerShimSpec) string {
	var b strings.Builder
	b.WriteString(tier2TrampolineFileHeader)
	for _, spec := range specs {
		appendTier2TrampolineBody(&b, spec)
	}
	return b.String()
}

// appendTier2TrampolineBody appends the Go source for one tier-2 shim trampoline to b.
// The body is a one-liner that captures the handler at compile time so Go's inliner can
// fold the indirect dispatch into a direct CALL.
//
// Takes b (*strings.Builder) which receives the appended Go source.
// Takes spec (Tier2HandlerShimSpec) which identifies the trampoline symbol and target
// handler.
func appendTier2TrampolineBody(b *strings.Builder, spec Tier2HandlerShimSpec) {
	name := strings.TrimSuffix(strings.TrimPrefix(spec.TrampolineSymbol, "·"), "(SB)")

	handler := tier2HandlerForTrampoline(name)
	b.WriteString("//nolint:unused // called from generated Plan-9 ASM via TEXT ·")
	b.WriteString(name)
	b.WriteString("(SB)\n")
	b.WriteString("//go:nosplit\n")
	b.WriteString("func ")
	b.WriteString(name)
	b.WriteString("(ctx *DispatchContext, instWord uint32) *DispatchContext {\n")
	if spec.IsNarrow {
		b.WriteString("\ttier2DispatchNarrow(ctx, instWord, ")
	} else {
		b.WriteString("\ttier2DispatchToHandler(ctx, instWord, ")
	}
	b.WriteString(handler)
	b.WriteString(")\n")
	b.WriteString("\treturn ctx\n")
	b.WriteString("}\n\n")
}

// tier2HandlerForTrampoline derives the Go handler function name.
//
// Convention: "asmCallHandleXxx" -> "handleXxx". Strip the "asmCall" prefix and lowercase
// the first letter of the remainder.
//
// Takes trampolineName (string) which is the trampoline function name (without leading
// dot or trailing (SB)).
//
// Returns the corresponding Go handler symbol.
func tier2HandlerForTrampoline(trampolineName string) string {
	rest := strings.TrimPrefix(trampolineName, "asmCall")
	if rest == "" {
		return trampolineName
	}
	return strings.ToLower(rest[:1]) + rest[1:]
}
