package vectormaths

// DotF64 computes the scalar dot product. Pure Go fallback selected by the safe build tag
// or the js+wasm build (the wasm runtime cannot execute the hand-written SIMD ASM).
//
// Takes a, b ([]float64) which are the equal-length operand vectors.
//
// Returns the scalar dot product sum(a[i]*b[i]).
func DotF64(a, b []float64) float64 {
	sum := 0.0
	for i := range a {
		sum += a[i] * b[i]
	}
	return sum
}
