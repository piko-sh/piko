package vectormaths

// dotF64Kern computes the dot product of two equal-length []float64 slices on arm64 using
// NEON. 8-way unrolled across V0/V4-V10 (2 doubles per accumulator, 16 doubles per
// iteration) using FMLA.2D to break the accumulator dependency chain.
//
// Takes a ([]float64) which is the first input vector.
// Takes b ([]float64) which is the second input vector (caller guarantees equal length).
//
// Returns the scalar dot product sum(a[i]*b[i]).
//
//go:noescape
func dotF64Kern(a, b []float64) float64

// DotF64 computes the scalar dot product of two equal-length []float64 slices on arm64.
// Routes through the NEON kernel generated by asmgen; the baseline arm64 ABI guarantees
// NEON so no runtime feature detection is required.
//
// Takes a, b ([]float64) which are the equal-length operand vectors.
//
// Returns the scalar dot product sum(a[i]*b[i]).
func DotF64(a, b []float64) float64 {
	return dotF64Kern(a, b)
}
