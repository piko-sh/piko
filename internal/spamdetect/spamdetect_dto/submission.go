package spamdetect_dto

import (
	"crypto/sha256"
	"encoding/hex"
	"maps"
	"net/netip"
	"slices"
	"strings"
	"time"
	"unicode/utf8"
)

const (
	// maxRemoteIPLength is the maximum byte length for the remote IP field before
	// normalisation. Inputs longer than this are length-clamped before netip parsing is
	// attempted.
	maxRemoteIPLength = 256

	// maxUserAgentLength is the maximum byte length for the user agent field.
	maxUserAgentLength = 1024

	// maxHoneypotLength is the maximum byte length for the honeypot field.
	maxHoneypotLength = 1024

	// maxPageURLLength is the maximum byte length for the page URL field.
	maxPageURLLength = 2048

	// maxActionNameLength is the maximum byte length for the action name field.
	maxActionNameLength = 256

	// maxMetadataEntries is the upper bound on metadata key-value pairs.
	maxMetadataEntries = 32

	// maxMetadataValueLen is the maximum byte length for a metadata value.
	maxMetadataValueLen = 1024

	// maxHeaderEntries is the upper bound on captured header entries.
	maxHeaderEntries = 16

	// maxHeaderValueLen is the maximum byte length for a header value.
	maxHeaderValueLen = 2048

	// maxMapKeyLength is the byte length cap for keys in sanitised maps. Keys above this are
	// dropped to keep map operations bounded.
	maxMapKeyLength = 256

	// normalisedIPHashLength is the hex character count used for hashing malformed remote
	// IPs. 16 hex characters supply 64 bits of collision resistance, sufficient for cache
	// key namespacing.
	normalisedIPHashLength = 16
)

// FieldValue carries a form field's string value alongside its semantic type from the
// schema.
type FieldValue struct {
	// Value is the string content of the field.
	Value string

	// Type is the semantic type from the schema.
	Type FieldType
}

// Submission carries the form field values and request metadata to be analysed for spam.
//
// Submissions are mutable; the service's Analyse method calls Sanitise which clamps
// oversize values, drops unknown fields, and assigns a random ID when one is not already
// set. Callers that need to retain the original input should copy it before passing to
// Analyse.
type Submission struct {
	// Fields contains form field values keyed by the schema field key.
	Fields map[string]FieldValue

	// Metadata carries provider context declared by the schema.
	//
	// Populated from the schema's Meta entries (e.g. form type, site URL).
	Metadata map[string]string

	// Headers carries selected HTTP request headers declared by the schema's CaptureHeader
	// entries.
	Headers map[string]string

	// FormSubmittedAt is when the form was submitted.
	FormSubmittedAt time.Time

	// FormLoadedAt is when the form was initially loaded (from a signed timestamp token).
	FormLoadedAt time.Time

	// ID is a unique identifier for this submission, generated by the service during
	// analysis. Used to correlate feedback reports.
	ID string

	// RemoteIP is the client IP address (without port).
	RemoteIP string

	// UserAgent is the client's User-Agent header.
	UserAgent string

	// HoneypotValue is the value of the hidden honeypot field.
	HoneypotValue string

	// PageURL is the page the form was submitted from.
	PageURL string

	// ActionName is the Piko action that received this submission.
	ActionName string

	// truncatedFields lists fields that were truncated or dropped during sanitisation.
	truncatedFields []string

	// truncated is true when any field was truncated during sanitisation.
	truncated bool
}

// Sanitise clamps field lengths to safe maximums using per-field limits from the schema,
// drops fields not declared in the schema, and normalises the RemoteIP to a canonical
// form.
//
// Mutates the submission. Repeat calls are idempotent.
//
// Takes schema (*Schema) which provides per-field length limits.
func (s *Submission) Sanitise(schema *Schema) {
	s.RemoteIP = NormaliseRemoteIP(s.RemoteIP)
	s.UserAgent = s.truncateAndTrack("UserAgent", s.UserAgent, maxUserAgentLength)
	s.HoneypotValue = s.truncateAndTrack("HoneypotValue", s.HoneypotValue, maxHoneypotLength)
	s.PageURL = s.truncateAndTrack("PageURL", s.PageURL, maxPageURLLength)
	s.ActionName = s.truncateAndTrack("ActionName", s.ActionName, maxActionNameLength)

	s.sanitiseMap("Metadata", s.Metadata, maxMetadataEntries, maxMetadataValueLen)
	s.sanitiseMap("Headers", s.Headers, maxHeaderEntries, maxHeaderValueLen)

	if schema == nil {
		return
	}

	schemaFields := schema.Fields()
	fieldLimits := make(map[string]int, len(schemaFields))
	for _, field := range schemaFields {
		fieldLimits[field.Key] = field.MaxLength
	}

	for key, fieldValue := range s.Fields {
		limit, exists := fieldLimits[key]
		if !exists {
			delete(s.Fields, key)
			s.markTruncated(key)
			continue
		}
		fieldValue.Value = s.truncateAndTrack(key, fieldValue.Value, limit)
		s.Fields[key] = fieldValue
	}
}

// WasTruncated reports whether any field value was truncated or dropped during
// sanitisation.
//
// Returns bool which is true when truncation occurred.
func (s *Submission) WasTruncated() bool {
	return s.truncated
}

// TruncatedFields returns a copy of the field keys that were truncated or dropped during
// sanitisation.
//
// Returns []string which contains the affected field keys.
func (s *Submission) TruncatedFields() []string {
	return slices.Clone(s.truncatedFields)
}

// FieldString returns the string value of a field by key, or an empty string if the key
// is not present.
//
// Takes key (string) which is the field key.
//
// Returns string which is the field value.
func (s *Submission) FieldString(key string) string {
	if s.Fields == nil {
		return ""
	}
	return s.Fields[key].Value
}

// GetField returns the full FieldValue for a key, or a zero value if the key is not
// present.
//
// Takes key (string) which is the field key.
//
// Returns FieldValue which is the field value and type.
func (s *Submission) GetField(key string) FieldValue {
	if s.Fields == nil {
		return FieldValue{}
	}
	return s.Fields[key]
}

// MetadataValue returns a metadata value by key, or an empty string.
//
// Takes key (string) which is the metadata key.
//
// Returns string which is the metadata value.
func (s *Submission) MetadataValue(key string) string {
	if s.Metadata == nil {
		return ""
	}
	return s.Metadata[key]
}

// HeaderValue returns a captured header value by name, or an empty string.
//
// Takes name (string) which is the header name.
//
// Returns string which is the header value.
func (s *Submission) HeaderValue(name string) string {
	if s.Headers == nil {
		return ""
	}
	return s.Headers[name]
}

// Clone returns a deep copy of the submission. Used by the service to freeze a snapshot
// for the feedback cache so subsequent caller mutations do not change the cached record.
//
// Returns *Submission which is the deep copy.
func (s *Submission) Clone() *Submission {
	if s == nil {
		return nil
	}
	clone := *s
	if s.Fields != nil {
		clone.Fields = maps.Clone(s.Fields)
	}
	if s.Metadata != nil {
		clone.Metadata = maps.Clone(s.Metadata)
	}
	if s.Headers != nil {
		clone.Headers = maps.Clone(s.Headers)
	}
	clone.truncatedFields = slices.Clone(s.truncatedFields)
	return &clone
}

// truncateAndTrack truncates a string and records the field key when shortened.
//
// Takes key (string) which is the field key, used for diagnostic tracking.
// Takes value (string) which is the string to truncate.
// Takes maximum (int) which is the byte length limit.
//
// Returns string which is the truncated value.
func (s *Submission) truncateAndTrack(key string, value string, maximum int) string {
	truncated := TruncateStringUTF8(value, maximum)
	if len(truncated) < len(value) {
		s.markTruncated(key)
	}
	return truncated
}

// markTruncated records that the given field key was truncated or dropped.
//
// Takes key (string) which is the affected field key.
func (s *Submission) markTruncated(key string) {
	s.truncated = true
	if key == "" {
		return
	}
	if slices.Contains(s.truncatedFields, key) {
		return
	}
	s.truncatedFields = append(s.truncatedFields, key)
}

// sanitiseMap truncates map values, drops oversized keys, and evicts excess entries.
//
// Takes name (string) which identifies the map for truncation tracking.
// Takes entries (map[string]string) which is the map to sanitise.
// Takes maxEntries (int) which is the maximum entry count.
// Takes maxValueLength (int) which is the maximum value byte length.
func (s *Submission) sanitiseMap(name string, entries map[string]string, maxEntries int, maxValueLength int) {
	for key := range entries {
		if len(key) > maxMapKeyLength {
			delete(entries, key)
			s.markTruncated(name)
		}
	}

	if len(entries) <= maxEntries {
		for key, value := range entries {
			entries[key] = s.truncateAndTrack(name, value, maxValueLength)
		}
		return
	}

	sortedKeys := make([]string, 0, len(entries))
	for key := range entries {
		sortedKeys = append(sortedKeys, key)
	}
	slices.Sort(sortedKeys)

	keepKeys := slices.Clone(sortedKeys[:maxEntries])
	keepSet := make(map[string]struct{}, maxEntries)
	for _, key := range keepKeys {
		keepSet[key] = struct{}{}
	}

	for _, key := range sortedKeys {
		if _, keep := keepSet[key]; !keep {
			delete(entries, key)
			s.markTruncated(name)
		} else {
			entries[key] = s.truncateAndTrack(name, entries[key], maxValueLength)
		}
	}
}

// TruncateStringUTF8 truncates a string to a maximum byte length, respecting rune
// boundaries so the returned value is always valid UTF-8.
//
// Takes value (string) which is the string to truncate.
// Takes maximum (int) which is the byte length limit.
//
// Returns string which is the truncated value.
func TruncateStringUTF8(value string, maximum int) string {
	if maximum < 0 {
		maximum = 0
	}
	if len(value) <= maximum {
		return value
	}
	if maximum == 0 {
		return ""
	}

	cut := maximum
	for cut > 0 && !utf8.RuneStart(value[cut]) {
		cut--
	}
	return value[:cut]
}

// NormaliseRemoteIP returns a canonical string form of a client IP suitable for cache
// keying and rate limiting.
//
// Valid IPv4 and IPv6 strings (with or without zone) are parsed via net/netip and
// returned in canonical form. Inputs that do not parse are length-clamped and hashed with
// SHA-256 (16 hex characters) so malformed values cannot bloat downstream cache keys.
//
// Takes value (string) which is the raw client IP.
//
// Returns string which is the normalised representation. Empty inputs return an empty
// string.
func NormaliseRemoteIP(value string) string {
	if value == "" {
		return ""
	}
	if len(value) > maxRemoteIPLength {
		value = value[:maxRemoteIPLength]
	}
	trimmed := strings.TrimSpace(value)
	if trimmed == "" {
		return ""
	}
	if addr, err := netip.ParseAddr(trimmed); err == nil {
		return addr.String()
	}
	sum := sha256.Sum256([]byte(trimmed))
	return hex.EncodeToString(sum[:])[:normalisedIPHashLength]
}
