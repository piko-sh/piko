func TestCreateImportSpecs(t *testing.T) {
	t.Parallel()

	packages := []string{
		"github.com/example/pkg1",
		"github.com/example/pkg2",
		"github.com/example/pkg3",
	}

	specs := createImportSpecs(packages)

	assert.Len(t, specs, 3, "Expected 3 import specs, got %d", len(specs))

	for i, spec := range specs {
		importSpec, ok := spec.(*ast.ImportSpec)
		require.True(t, ok, "Expected *ast.ImportSpec, got %T", spec)

		assert.Equal(t, "_", importSpec.Name.Name,
			"Import %d should have blank identifier, got: %s", i, importSpec.Name.Name)

		require.NotNil(t, importSpec.Path, "Import path should not be nil")

		assert.Equal(t, token.STRING, importSpec.Path.Kind,
			"Import path should be STRING kind, got: %v", importSpec.Path.Kind)

		assert.False(t, !strings.HasPrefix(importSpec.Path.Value, `"`) || !strings.HasSuffix(importSpec.Path.Value, `"`),
			"Import path should be quoted, got: %s", importSpec.Path.Value)
	}
}

func TestCreateImportSpecs_Sorting(t *testing.T) {
	t.Parallel()

	packages := []string{
		"github.com/zzz/pkg",
		"github.com/aaa/pkg",
		"github.com/mmm/pkg",
	}

	specs := createImportSpecs(packages)

	paths := make([]string, 0, len(specs))
	for _, spec := range specs {
		importSpec, ok := spec.(*ast.ImportSpec)
		require.True(t, ok, "spec should be *ast.ImportSpec")

		path := strings.Trim(importSpec.Path.Value, `"`)
		paths = append(paths, path)
	}

	assert.Equal(t, "github.com/aaa/pkg", paths[0], "First import should be github.com/aaa/pkg, got: %s", paths[0])
	assert.Equal(t, "github.com/mmm/pkg", paths[1], "Second import should be github.com/mmm/pkg, got: %s", paths[1])
	assert.Equal(t, "github.com/zzz/pkg", paths[2], "Third import should be github.com/zzz/pkg, got: %s", paths[2])
}

