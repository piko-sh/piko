func TestGenerate_DeterministicOutput(t *testing.T) {
	t.Parallel()

	ctx := context.Background()
	mockWriter := &generator_domain.MockFSWriter{}
	emitter := NewRegisterEmitter(mockWriter)

	packages := []string{
		"github.com/example/pkg3",
		"github.com/example/pkg1",
		"github.com/example/pkg2",
	}

	code1, err1 := emitter.Generate(ctx, packages)
	require.NoError(t, err1, "First generation failed")

	code2, err2 := emitter.Generate(ctx, packages)
	require.NoError(t, err2, "Second generation failed")

	assert.Equal(t, string(code1), string(code2), "Generate should produce deterministic output")

	codeString := string(code1)
	package1Position := strings.Index(codeString, "pkg1")
	package2Position := strings.Index(codeString, "pkg2")
	package3Position := strings.Index(codeString, "pkg3")

	require.False(t, package1Position == -1 || package2Position == -1 || package3Position == -1,
		"All packages should be present in generated code")

	assert.False(t, package1Position >= package2Position || package2Position >= package3Position,
		"Packages should be sorted in alphabetical order")
}

