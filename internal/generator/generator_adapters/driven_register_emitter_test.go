func TestGenerate_SinglePackage(t *testing.T) {
	t.Parallel()

	ctx := context.Background()
	mockWriter := &generator_domain.MockFSWriter{}
	emitter := NewRegisterEmitter(mockWriter)

	packages := []string{"github.com/example/project/dist/pages/home"}

	code, err := emitter.Generate(ctx, packages)

	require.NoError(t, err, "Generate failed")

	codeString := string(code)

	assert.Contains(t, codeString, `_ "github.com/example/project/dist/pages/home"`,
		"Generated code should contain the package import")

	fset := token.NewFileSet()
	fileAST, parseErr := parser.ParseFile(fset, "test.go", code, parser.AllErrors)
	assert.NoError(t, parseErr, "Generated code is not valid Go: %v\nCode:\n%s", parseErr, string(code))

	assert.Equal(t, "dist", fileAST.Name.Name, "Expected package name 'dist', got: %s", fileAST.Name.Name)

	foundImport := false
	for _, declaration := range fileAST.Decls {
		if genDecl, ok := declaration.(*ast.GenDecl); ok && genDecl.Tok == token.IMPORT {
			foundImport = true
			assert.Len(t, genDecl.Specs, 1, "Expected 1 import spec, got %d", len(genDecl.Specs))
		}
	}

	assert.True(t, foundImport, "Generated code should contain an import declaration")
}

