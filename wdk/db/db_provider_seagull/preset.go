const (
	// pikoPrefix is Piko's directive, generated-helper and generated-error prefix.
	pikoPrefix = "piko"

	// pikoNamespace prefixes Piko's persisted migration and seed tables and locks.
	pikoNamespace = "piko"

	// pikoHeader is the header of every file Piko generates for SQL access.
	pikoHeader = "// Code generated by Piko. DO NOT EDIT."

	// mathsPackage is the import path of Piko's precise numeric types.
	mathsPackage = "piko.sh/piko/wdk/maths"

	// jsonPackage is the import path of Piko's JSON column type and scan adapter.
	jsonPackage = "piko.sh/piko/wdk/db/dbjson"

	// queryNamesFile is the file the query-name resolver is generated into.
	queryNamesFile = "otel.go"

	// queryNamesFunction is the name of the generated query-name resolver, which Piko's
	// database instrumentation calls.
	queryNamesFunction = "QueryNameResolver"

	// sqliteInteger is the SQLite type Piko reads as a 32-bit integer.
	sqliteInteger = "integer"

	// goInt32 is the Go type Piko reads a SQLite integer into.
	goInt32 = "int32"
)

// pikoPreset returns the Seagull preset that reproduces Piko's generated code exactly.
//
// SQL constants keep Piko's names, the query name lowercased with no suffix, and enum
// columns stay strings rather than named Go types.
//
// Returns seagull.Preset which uses Piko's prefixes, header, constant names, type slots
// and query-name resolver.
func pikoPreset() seagull.Preset {
	decimal := seagull.Slot{
		NotNull:  seagull.GoType{Package: mathsPackage, Name: "Decimal"},
		Nullable: seagull.GoType{Package: mathsPackage, Name: "*Decimal"},
	}
	document := seagull.GoType{Package: jsonPackage, Name: "JSON"}
	return seagull.Preset{
		Directives: seagull.Directives{
			Canonical:        pikoPrefix,
			Aliases:          nil,
			Foreign:          nil,
			RequireCanonical: false,
		},
		Header:               pikoHeader,
		HelperPrefix:         pikoPrefix,
		ErrorPrefix:          pikoPrefix,
		SQLConstantSuffix:    "",
		SQLConstantLowerCase: true,
		NonNullElements:      true,
		KeepStars:            true,
		QueryNames: seagull.QueryNames{
			Enabled:  true,
			File:     queryNamesFile,
			Function: queryNamesFunction,
		},
		Types: seagull.TypeSlots{
			Decimal: decimal,
			Money:   decimal,
			BigInt: seagull.Slot{
				NotNull:  seagull.GoType{Package: mathsPackage, Name: "BigInt"},
				Nullable: seagull.GoType{Package: mathsPackage, Name: "*BigInt"},
			},
			JSON: seagull.Slot{NotNull: document, Nullable: document},
			JSONScanInto: seagull.Slot{
				NotNull:  seagull.GoType{Package: jsonPackage, Name: "ScanInto"},
				Nullable: seagull.GoType{Package: "", Name: ""},
			},
			Enum: seagull.Slot{
				NotNull:  seagull.GoType{Package: "", Name: "string"},
				Nullable: seagull.GoType{Package: "", Name: "*string"},
			},
		},
	}
}

// presetTypeOverrides preserves Piko's generated types, including int32 for SQLite
// INTEGER.
//
// Takes facts (*dialect.Facts) which describe the dialect being generated for.
//
// Returns []seagull.TypeOverride which is empty outside the SQLite family.
func presetTypeOverrides(facts *dialect.Facts) []seagull.TypeOverride {
	if facts.Family != dialect_engine_sqlite.Family {
		return nil
	}
	return []seagull.TypeOverride{{SQLTypeName: sqliteInteger, GoName: goInt32}}
}

// mergeTypeOverrides combines preset and request overrides, with case-insensitive request
// matches taking precedence.
//
// Takes preset ([]seagull.TypeOverride) which are Piko's defaults.
// Takes requested ([]seagull.TypeOverride) which are the request's overrides.
//
// Returns []seagull.TypeOverride which holds the kept preset overrides, then the
// request's.
func mergeTypeOverrides(preset, requested []seagull.TypeOverride) []seagull.TypeOverride {
	merged := make([]seagull.TypeOverride, 0, len(preset)+len(requested))
	for _, override := range preset {
		if !namesSQLType(requested, override.SQLTypeName) {
			merged = append(merged, override)
		}
	}
	return append(merged, requested...)
}

// namesSQLType reports whether any of overrides is for the SQL type name, ignoring case.
//
// Takes overrides ([]seagull.TypeOverride) which are searched.
// Takes sqlTypeName (string) which is the SQL type name to find.
//
// Returns bool which is true when an override names the type.
func namesSQLType(overrides []seagull.TypeOverride, sqlTypeName string) bool {
	for _, override := range overrides {
		if override.SQLTypeName != "" && strings.EqualFold(override.SQLTypeName, sqlTypeName) {
			return true
		}
	}
	return false
}

// pikoRuntimeTables returns the tables Piko's migration and seed runtime keeps in a
// database, so a schema read from a live database leaves them out.
//
// Returns []string which holds the history, seed and lock table names.
func pikoRuntimeTables() []string {
	names := migrate_backend_sqlite.New(migrate.WithNamespace(pikoNamespace)).Names()
	return []string{names.History, names.Seeds, names.MigrationLock, names.SeedLock}
}
