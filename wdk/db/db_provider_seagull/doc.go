// Package db_provider_seagull is the bridge between Piko's database layer and Seagull,
// the SQL analyser, code generator and migration runner behind Piko's querier
// (https://github.com/piko-sh/seagull).
//
// It is the only place that knows both vocabularies. Piko's root module never depends on
// Seagull: the database engine modules (wdk/db/db_engine_*) depend on this bridge, so
// applications that register no database pull in no SQL toolchain at all.
//
// Everything Seagull produces keeps Piko's established shape: the `piko.` directive
// prefix, the "// Code generated by Piko. DO NOT EDIT." header, the piko_* migration and
// seed tables and lock keys (MySQL's server-wide), generated code that uses wdk/maths and
// wdk/db/dbjson, lowercased SQL constant names, string enums and int32 SQLite integers,
// the otel.go query-name resolver, and Piko's OpenTelemetry span and metric names. Values
// are copied between the two vocabularies rather than aliased, and errors match Piko's
// sentinels and typed errors as well as Seagull's.
//
// # Custom dialects
//
// [NewEngine] wraps any Seagull dialect as a Piko engine configuration. It is the escape
// hatch for projects that configure a built-in engine beyond what [DialectOptions]
// carries, such as sdk/dialect/dialect_engine_postgres with its search path, and it
// leaves Piko's vocabulary: the dialect is a seagull.sh/seagull/sdk/dialect.Dialect.
