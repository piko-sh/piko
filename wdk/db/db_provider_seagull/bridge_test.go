func TestTranslateErrorSentinels(t *testing.T) {
	t.Parallel()

	require.NoError(t, translateError(nil))

	unrelated := errors.New("unrelated")
	require.Same(t, unrelated, translateError(unrelated))

	for _, pair := range sentinelPairs {
		wrapped := fmt.Errorf("context: %w", pair.seagull)
		translated := translateError(wrapped)
		require.ErrorIs(t, translated, pair.piko)
		require.ErrorIs(t, translated, pair.seagull)
		require.Equal(t, wrapped.Error(), translated.Error())
	}
	require.ErrorIs(t, translateError(seagull.ErrMalformedSQL), sqldb_domain.ErrMalformedSQLStatement)
	require.ErrorIs(t, translateError(migrate.ErrInvalidIdentifier), sqldb_domain.ErrInvalidIdentifier)
}

func TestTranslateErrorTypedErrors(t *testing.T) {
	t.Parallel()

	cause := errors.New("boom")
	cases := []struct {
		seagull error
		check   func(t *testing.T, translated error)
	}{
		{seagull: &migrate.ChecksumMismatchError{AppliedChecksum: "a", FileChecksum: "b", Name: "n", Version: 1}, check: func(t *testing.T, translated error) {
			target, ok := errors.AsType[*sqldb_domain.ChecksumMismatchError](translated)
			require.True(t, ok)
			require.Equal(t, "b", target.FileChecksum)
		}},
		{seagull: &migrate.DownChecksumMismatchError{RecordedChecksum: "a", FileChecksum: "b", Name: "n", Version: 1}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.DownChecksumMismatchError](translated)
			require.True(t, ok)
		}},
		{seagull: &migrate.MigrationExecutionError{Cause: cause, Name: "n", Version: 2, Direction: migrate.MigrationDirectionDown}, check: func(t *testing.T, translated error) {
			target, ok := errors.AsType[*sqldb_domain.MigrationExecutionError](translated)
			require.True(t, ok)
			require.Equal(t, sqldb_dto.DirectionDown, target.Direction)
			require.ErrorIs(t, translated, cause)
		}},
		{seagull: &migrate.LockAcquisitionError{Cause: cause}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.LockAcquisitionError](translated)
			require.True(t, ok)
		}},
		{seagull: &migrate.MissingMigrationFileError{Name: "n", Version: 3}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.MissingMigrationFileError](translated)
			require.True(t, ok)
		}},
		{seagull: &migrate.NoDownMigrationError{Version: 4}, check: func(t *testing.T, translated error) {
			require.ErrorIs(t, translated, sqldb_domain.ErrNoDownMigration)
		}},
		{seagull: &migrate.DuplicateMigrationVersionError{FirstFilename: "a", SecondFilename: "b", Version: 5, Direction: migrate.MigrationDirectionUp}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.DuplicateMigrationVersionError](translated)
			require.True(t, ok)
		}},
		{seagull: &migrate.DirtyMigrationError{Version: 6, LastStatement: 2}, check: func(t *testing.T, translated error) {
			target, ok := errors.AsType[*sqldb_domain.DirtyMigrationError](translated)
			require.True(t, ok)
			require.Equal(t, 2, target.LastStatement)
		}},
		{seagull: &migrate.ResumeMismatchError{Name: "n", Version: 9, LastStatement: 3, RecordedSplitterVersion: 0, SplitterVersion: 1, StatementCount: 5}, check: func(t *testing.T, translated error) {
			target, ok := errors.AsType[*sqldb_domain.DirtyMigrationError](translated)
			require.True(t, ok)
			require.Equal(t, int64(9), target.Version)
			require.Equal(t, 3, target.LastStatement)
		}},
		{seagull: &migrate.DuplicateSeedVersionError{FirstFilename: "a", SecondFilename: "b", Version: 7}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.DuplicateSeedVersionError](translated)
			require.True(t, ok)
		}},
		{seagull: &migrate.SeedExecutionError{Cause: cause, Name: "s", Version: 8}, check: func(t *testing.T, translated error) {
			_, ok := errors.AsType[*sqldb_domain.SeedExecutionError](translated)
			require.True(t, ok)
		}},
	}

	for _, testCase := range cases {
		translated := translateError(fmt.Errorf("wrapped: %w", testCase.seagull))
		require.ErrorIs(t, translated, testCase.seagull)
		testCase.check(t, translated)
	}
}

