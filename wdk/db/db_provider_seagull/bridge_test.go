func TestConversions(t *testing.T) {
	t.Parallel()

	require.Equal(t, []sqldb_dto.GeneratedFile{{Name: "a.go", Content: []byte("x")}},
		fromSeagullFiles([]emit.GeneratedFile{{Name: "a.go", Content: []byte("x")}}))
	require.Nil(t, fromSeagullDiagnostics(nil))
	converted := fromSeagullDiagnostics([]seagull.SourceError{
		{Filename: "q.sql", Message: "m", Code: "Q001", Suggestion: "s", Line: 1, Column: 2, EndLine: 3, EndColumn: 4, Severity: seagull.SeverityWarning},
		{Severity: seagull.SeverityHint},
		{Severity: seagull.SeverityError},
	})
	require.Equal(t, sqldb_dto.SourceError{Filename: "q.sql", Message: "m", Code: "Q001", Suggestion: "s", Line: 1, Column: 2, EndLine: 3, EndColumn: 4, Severity: sqldb_dto.SeverityWarning}, converted[0])
	require.Equal(t, sqldb_dto.SeverityHint, converted[1].Severity)
	require.Equal(t, sqldb_dto.SeverityError, converted[2].Severity)
	require.Nil(t, toSeagullTypeOverrides(nil))
	require.Nil(t, toSeagullCustomFunctions(nil))
	require.Equal(t, sqldb_dto.MigrationRunHookContext{PendingVersions: []int64{1}, PendingCount: 1, Direction: sqldb_dto.DirectionUp},
		fromSeagullRunHookContext(migrate.MigrationRunHookContext{PendingVersions: []int64{1}, PendingCount: 1, Direction: migrate.MigrationDirectionUp}))
}

