func TestMigrationsAndSeedsAgainstSQLite(t *testing.T) {
	t.Parallel()

	ctx := context.Background()
	database, err := sql.Open("sqlite", "file:"+t.TempDir()+"/bridge.db")
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, database.Close()) })

	migrations := fstest.MapFS{
		"migrations/001_users.up.sql":   {Data: []byte("CREATE TABLE users (id INTEGER PRIMARY KEY, email TEXT NOT NULL);\n")},
		"migrations/001_users.down.sql": {Data: []byte("DROP TABLE users;\n")},
		"seeds/001_users.sql":           {Data: []byte("INSERT INTO users (email) VALUES ('ada@example.com');\n")},
	}

	var events []string
	config := sqldb_domain.BuildMigrationServiceConfig(
		sqldb_domain.WithBeforeRun(func(_ context.Context, hook sqldb_dto.MigrationRunHookContext) error {
			events = append(events, fmt.Sprintf("before-run:%d", hook.PendingCount))
			return nil
		}),
		sqldb_domain.WithBeforeMigration(func(_ context.Context, hook sqldb_dto.MigrationHookContext) error {
			events = append(events, "before:"+hook.Name)
			return nil
		}),
		sqldb_domain.WithAfterMigration(func(_ context.Context, hook sqldb_dto.MigrationHookContext) error {
			events = append(events, "after:"+hook.Name)
			return nil
		}),
		sqldb_domain.WithAfterRun(func(_ context.Context, _ sqldb_dto.MigrationRunHookContext, applied int) error {
			events = append(events, fmt.Sprintf("after-run:%d", applied))
			return nil
		}),
		sqldb_domain.WithNonBlockingLock(),
	)

	toolchain := NewToolchain(dialect_engine_sqlite.New())
	migrator, err := toolchain.NewMigrationService(database, db.SQLiteDialect(), migrations, "migrations", config)
	require.NoError(t, err)

	applied, err := migrator.Up(ctx)
	require.NoError(t, err)
	require.Equal(t, 1, applied)
	require.Equal(t, []string{"before-run:1", "before:users", "after:users", "after-run:1"}, events)

	var historyRows int
	require.NoError(t, database.QueryRowContext(ctx, "SELECT count(*) FROM piko_migrations").Scan(&historyRows))
	require.Equal(t, 1, historyRows)

	statuses, err := migrator.Status(ctx)
	require.NoError(t, err)
	require.Len(t, statuses, 1)
	require.True(t, statuses[0].Applied)
	require.True(t, statuses[0].HasDownMigration)
	require.NoError(t, migrator.Validate(ctx))

	seeder, err := toolchain.NewSeedService(database, db.SQLiteDialect(), migrations, "seeds")
	require.NoError(t, err)
	seeded, err := seeder.Apply(ctx)
	require.NoError(t, err)
	require.Equal(t, 1, seeded)
	seedStatuses, err := seeder.Status(ctx)
	require.NoError(t, err)
	require.Len(t, seedStatuses, 1)
	reseeded, err := seeder.Reseed(ctx)
	require.NoError(t, err)
	require.Equal(t, 1, reseeded)

	var seedRows int
	require.NoError(t, database.QueryRowContext(ctx, "SELECT count(*) FROM piko_seeds").Scan(&seedRows))
	require.Equal(t, 1, seedRows)

	reverted, err := migrator.Down(ctx, 1)
	require.NoError(t, err)
	require.Equal(t, 1, reverted)
	_, err = migrator.UpTo(ctx, 1)
	require.NoError(t, err)
	_, err = migrator.DownTo(ctx, 0)
	require.NoError(t, err)
}

