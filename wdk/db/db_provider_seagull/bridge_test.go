func TestGenerateThroughTheBridge(t *testing.T) {
	t.Parallel()

	files := fstest.MapFS{
		"migrations/001_users.up.sql": {Data: []byte("CREATE TABLE users (id INTEGER PRIMARY KEY, email TEXT NOT NULL, balance NUMERIC, external_id BLOB);\n")},
		"queries/users.sql":           {Data: []byte("-- piko.query(GetUser, one)\nSELECT id, email, balance FROM users WHERE id = ?;\n")},
	}

	result, err := NewToolchain(dialect_engine_sqlite.New()).Generate(context.Background(), sqldb_dto.GenerateRequest{
		Files:              files,
		MigrationDirectory: "migrations",
		QueryDirectory:     "queries",
		Driver:             sqldb_dto.DriverDatabaseSQL,
		TypeOverrides:      []sqldb_dto.TypeOverride{{SQLTypeName: "blob", GoPackage: "example.com/ids", GoName: "ID"}},
		CustomFunctions:    []sqldb_dto.CustomFunction{{Name: "similarity", ReturnType: "real", Nullable: "never_null", Arguments: []string{"text", "text"}}},
	})

	require.NoError(t, err)
	require.Equal(t, 1, result.QueryCount)
	require.Empty(t, result.Diagnostics)
	contents := make(map[string]string, len(result.Files))
	for _, file := range result.Files {
		contents[file.Name] = string(file.Content)
	}
	require.Contains(t, contents, "otel.go")
	require.Contains(t, contents["models.go"], "// Code generated by Piko. DO NOT EDIT.")
	require.Contains(t, contents["models.go"], `"piko.sh/piko/wdk/maths"`)
	require.Contains(t, contents["models.go"], `"example.com/ids"`)
	require.Contains(t, contents["otel.go"], "func QueryNameResolver")
}

