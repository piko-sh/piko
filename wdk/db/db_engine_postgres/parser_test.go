func TestApplyDDLReportsSyntaxErrorsWithoutPanicking(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name         string
		sql          string
		wantContains string
	}{
		{name: "unbalanced column CHECK", sql: "CREATE TABLE t (x int CHECK (x > 1", wantContains: "unmatched parenthesis"},
		{name: "unbalanced column DEFAULT", sql: "CREATE TABLE t (x int DEFAULT (1", wantContains: "unmatched parenthesis"},
		{name: "unbalanced GENERATED ALWAYS AS", sql: "CREATE TABLE t (x int GENERATED ALWAYS AS (1", wantContains: "unmatched parenthesis"},
		{name: "unbalanced identity options", sql: "CREATE TABLE t (x int GENERATED ALWAYS AS IDENTITY (START 1", wantContains: "unmatched parenthesis"},
		{name: "unbalanced BY DEFAULT identity", sql: "CREATE TABLE t (x int GENERATED BY DEFAULT AS IDENTITY (START 1", wantContains: "unmatched parenthesis"},
		{name: "malformed REFERENCES target", sql: "CREATE TABLE t (x int REFERENCES s.)", wantContains: "expected identifier"},
		{name: "unbalanced REFERENCES columns", sql: "CREATE TABLE t (x int REFERENCES s (id", wantContains: "unmatched parenthesis"},
		{name: "unbalanced table CHECK", sql: "CREATE TABLE t (x int, CHECK (x > 1", wantContains: "unmatched parenthesis"},
		{name: "unbalanced EXCLUDE", sql: "CREATE TABLE t (x int, EXCLUDE USING gist (x WITH =", wantContains: "unmatched parenthesis"},
		{name: "drop extension without a name", sql: "DROP EXTENSION IF EXISTS", wantContains: "expected identifier"},
		{name: "drop function with unbalanced arguments", sql: "DROP FUNCTION f(int", wantContains: "unmatched parenthesis"},
		{name: "comment on function with unbalanced arguments", sql: "COMMENT ON FUNCTION f(((", wantContains: "unmatched parenthesis"},
		{name: "alter table set with unbalanced options", sql: "ALTER TABLE t SET (fillfactor = 70", wantContains: "unmatched parenthesis"},
		{name: "alter type rename value without TO", sql: "ALTER TYPE mood RENAME VALUE 'a' INTO 'b'", wantContains: "expected keyword [TO]"},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			err := applyDDLExpectError(t, testCase.sql)

			require.Error(t, err)
			assert.Contains(t, err.Error(), testCase.wantContains)
			assert.NotContains(t, err.Error(), "panic")
		})
	}
}

func TestAnalyseQueryReportsSyntaxErrorsWithoutPanicking(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name         string
		sql          string
		wantContains string
	}{
		{name: "set operation arm without SELECT", sql: "SELECT 1 UNION 2", wantContains: "expected keyword [SELECT]"},
		{name: "insert into a malformed name", sql: "INSERT INTO s.(a) VALUES (1)", wantContains: "expected identifier"},
		{name: "update with a malformed name", sql: "UPDATE s.(a) SET a = 1", wantContains: "expected identifier"},
		{name: "update without SET", sql: "UPDATE t WHERE a = 1", wantContains: "expected keyword [SET]"},
		{name: "delete without FROM", sql: "DELETE t WHERE a = 1", wantContains: "expected keyword [FROM]"},
		{name: "delete from a malformed name", sql: "DELETE FROM s.(a) WHERE a = 1", wantContains: "expected identifier"},
		{name: "join with unbalanced USING", sql: "SELECT * FROM a JOIN b USING (id", wantContains: "unmatched parenthesis"},
		{name: "join to a malformed table name", sql: "SELECT * FROM a JOIN s.(x) ON true", wantContains: "expected identifier"},
		{name: "derived table with unbalanced column aliases", sql: "SELECT * FROM (SELECT 1) AS d (a", wantContains: "unmatched parenthesis"},
		{name: "on conflict with unbalanced target", sql: "INSERT INTO t (a) VALUES (1) ON CONFLICT (a", wantContains: "unmatched parenthesis"},
		{name: "malformed scalar subquery fails the statement", sql: "SELECT (SELECT 1 UNION 2) AS x", wantContains: "expected keyword [SELECT]"},
		{name: "unbalanced ANY subquery", sql: "SELECT a = ANY (SELECT 1 FROM t", wantContains: "unmatched parenthesis"},
		{name: "unbalanced CAST type modifiers", sql: "SELECT CAST(a AS numeric(10, 2 AS x FROM t", wantContains: "unmatched parenthesis"},
		{name: "unbalanced cast operator type modifiers", sql: "SELECT a::numeric(10 AS x FROM t", wantContains: "unmatched parenthesis"},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			engine := NewPostgresEngine()
			statements, err := engine.ParseStatements(testCase.sql)
			require.NoError(t, err)
			require.NotEmpty(t, statements)

			_, err = engine.AnalyseQuery(newPostgresCatalogue(), statements[0])

			require.Error(t, err)
			assert.Contains(t, err.Error(), testCase.wantContains)
			assert.NotContains(t, err.Error(), "panic")
		})
	}
}

func TestRecordSyntaxErrorKeepsTheFirstError(t *testing.T) {
	t.Parallel()

	first := errors.New("first")
	p := newParser(nil)
	child := p.newChildParser(nil)

	assert.NoError(t, p.recordSyntaxError(nil))
	assert.Same(t, first, child.recordSyntaxError(first))
	assert.Error(t, p.recordSyntaxError(errors.New("second")))

	assert.Same(t, first, p.syntax.err, "a child shares the statement-wide record and the first error wins")
}

func TestRequireHelpersRecordSyntaxErrors(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		run  func(p *parser) error
		name string
		sql  string
	}{
		{
			name: "keyword sequence stops at the first mismatch",
			sql:  "DROP VIEW v",
			run:  func(p *parser) error { return p.requireKeywordSequence(keywordDROP, keywordTABLE) },
		},
		{
			name: "identifier",
			sql:  "(",
			run: func(p *parser) error {
				_, err := p.requireIdentifierOrKeyword()
				return err
			},
		},
		{
			name: "schema-qualified name",
			sql:  "s.",
			run: func(p *parser) error {
				_, _, err := p.requireSchemaQualifiedName()
				return err
			},
		},
		{
			name: "parenthesised group",
			sql:  "(a",
			run:  func(p *parser) error { return p.requireSkipParenthesised() },
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			tokens, err := tokenise(testCase.sql)
			require.NoError(t, err)
			p := newParser(tokens)

			runErr := testCase.run(p)

			require.Error(t, runErr)
			assert.Same(t, runErr, p.syntax.err)
		})
	}
}

func TestApplyDDLStillRunsPostParseHooksForUnhandledStatements(t *testing.T) {
	t.Parallel()

	hookCalls := 0
	engine := NewPostgresEngine(WithMaxTokensPerStatement(1), WithPostParseHook(
		func(_ ParserContext, _ StatementKind, _ *querier_dto.CatalogueMutation) error {
			hookCalls++
			return nil
		},
	))
	statements, err := engine.ParseStatements("INSERT INTO t VALUES (1, 2, 3)")
	require.NoError(t, err)

	mutation, err := engine.ApplyDDL(context.Background(), statements[0])

	require.NoError(t, err)
	assert.Nil(t, mutation)
	assert.Equal(t, 1, hookCalls)
}

func TestCollectParenthesised(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name       string
		sql        string
		wantValues []string
		wantErr    bool
	}{
		{name: "nested group", sql: "(a, (b)) tail", wantValues: []string{"a", ",", "(", "b", ")"}},
		{name: "empty group", sql: "() tail", wantValues: nil},
		{name: "unmatched group", sql: "(a, (b) tail", wantErr: true},
		{name: "not a group", sql: "a", wantErr: true},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			tokens, err := tokenise(testCase.sql)
			require.NoError(t, err)
			p := newParser(tokens)

			inner, err := p.collectParenthesised()

			if testCase.wantErr {
				require.Error(t, err)
				return
			}
			require.NoError(t, err)
			var values []string
			for _, tok := range inner {
				values = append(values, tok.value)
			}
			assert.Equal(t, testCase.wantValues, values)
			assert.Equal(t, "tail", p.current().value)
		})
	}
}

func TestCollectParenthesisedReturnsAReadOnlyView(t *testing.T) {
	t.Parallel()

	tokens, err := tokenise("(a) b")
	require.NoError(t, err)
	p := newParser(tokens)

	inner, err := p.collectParenthesised()
	require.NoError(t, err)
	extended := append(inner, token{kind: tokenIdentifier, value: "x", position: 0})

	assert.Equal(t, "x", extended[1].value)
	assert.Equal(t, ")", p.tokens[2].value, "appending to the view must not overwrite the parser's tokens")
}
