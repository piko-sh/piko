func TestRepositoryCountsAuthoredSourcesAndCompositions(t *testing.T) {
	files := fstest.MapFS{}
	for _, name := range []string{"examples/scenarios/one/src/pages/main.pk", "examples/scenarios/one/src/partials/repeat.pk", "examples/scenarios/two/src/pages/home.pk", "examples/scenarios/two/src/dist/copied.pk", "examples/scenarios/two/src/vendor/other.pk", "tests/integration/demo/testdata/invalid/src/pages/failing.pk"} {
		files[name] = &fstest.MapFile{Data: []byte(`<template><table><tbody><tr p-for="r in state.rows"><td p-text="r"></td></tr></tbody></table><svg><foreignObject><div></div></foreignObject></svg></template>`)}
	}
	files["tests/integration/demo/testdata/invalid/testspec.json"] = &fstest.MapFile{Data: []byte(`{"shouldGenerateError":true}`)}
	corpus, err := Repository(t.Context(), files)
	require.NoError(t, err)
	population := corpus.Populations["examples"]
	require.NotNil(t, population)
	assert.Equal(t, 3, population.Files, "included wrong sources")
	assert.Equal(t, 2, population.Projects, "included wrong projects")
	for _, feature := range []string{"parent/tr>td", "binding/tr/p-for", "source-namespace/html/div", "source-namespace/svg/foreignobject"} {
		assert.Equal(t, Frequency{Files: 3, Projects: 2}, population.Features[".pk/"+feature], feature)
	}
	invalid := corpus.Populations["integration-expected-error"]
	require.NotNil(t, invalid, "expected-error fixture missing")
	assert.Equal(t, 1, invalid.Files)
}

func TestRepositoryStopsWhenCancelled(t *testing.T) {
	files := fstest.MapFS{"examples/scenarios/one/src/pages/main.pk": &fstest.MapFile{Data: []byte(`<template><p>x</p></template>`)}}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	_, err := Repository(ctx, files)
	require.ErrorIs(t, err, context.Canceled)
}

func TestNegativeFixtureRejectsInvalidSpecification(t *testing.T) {
	files := fstest.MapFS{"fixture/testspec.json": &fstest.MapFile{Data: []byte(`{`)}}
	_, err := negativeFixture(files, "fixture")
	require.ErrorContains(t, err, "fixture/testspec.json")
	negative, err := negativeFixture(files, "absent")
	require.NoError(t, err)
	assert.False(t, negative)
}

func TestGeneratedGoRecognisesMarkerBeforePackage(t *testing.T) {
	assert.True(t, generatedGo([]byte("// Code generated by tool. DO NOT EDIT.\npackage x\n")))
	assert.False(t, generatedGo([]byte("package x\n// Code generated by tool. DO NOT EDIT.\n")))
	assert.False(t, generatedGo([]byte("// Ordinary comment.\npackage x\n")))
}

func TestHasAuthoredFiles(t *testing.T) {
	files := fstest.MapFS{
		"authored/src/pages/main.pk":      {},
		"readme-only/README.md":           {},
		"build-output/src/bin/generator":  {},
		"build-output/src/.piko/wal/data": {},
		"build-output/src/dist/main.js":   {},
		"empty/src":                       &fstest.MapFile{Mode: fs.ModeDir},
	}
	testCases := []struct {
		name      string
		directory string
		want      bool
	}{
		{name: "a directory with a page has authored files", directory: "authored", want: true},
		{name: "a directory with only a readme has authored files", directory: "readme-only", want: true},
		{name: "a directory with only build output has no authored files", directory: "build-output", want: false},
		{name: "an empty directory has no authored files", directory: "empty", want: false},
	}
	for _, tt := range testCases {
		t.Run(tt.name, func(t *testing.T) {
			got, err := hasAuthoredFiles(files, tt.directory)
			require.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

func TestHasAuthoredFilesReportsAMissingDirectory(t *testing.T) {
	_, err := hasAuthoredFiles(fstest.MapFS{}, "missing")
	require.ErrorIs(t, err, fs.ErrNotExist)
}
