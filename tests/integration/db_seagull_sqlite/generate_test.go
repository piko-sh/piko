package db_seagull_sqlite_test

import (
	"context"
	"flag"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"piko.sh/piko/wdk/db"
	"piko.sh/piko/wdk/db/db_engine_sqlite"
)

const (
	generatedDirectory = "store"
	generatedHeader    = "// Code generated by Piko. DO NOT EDIT."
)

var (
	updateGenerated = flag.Bool("update", false, "Rewrite the generated store package")
)

func generateStore(t *testing.T) *db.GenerationResult {
	t.Helper()

	result, err := db.Generate(context.Background(), db_engine_sqlite.SQLite(), db.GenerateRequest{
		Files:              os.DirFS(filepath.Join("testdata", "db")),
		PackageName:        generatedDirectory,
		MigrationDirectory: "migrations",
		QueryDirectory:     "queries",
		TypeOverrides:      nil,
		CustomFunctions:    nil,
		Driver:             db.DriverDatabaseSQL,
	})
	require.NoError(t, err)
	for _, diagnostic := range result.Diagnostics {
		require.NotEqual(t, db.SeverityError, diagnostic.Severity, "%s:%d: %s", diagnostic.Filename, diagnostic.Line, diagnostic.Message)
	}
	return result
}

func TestGenerateMatchesCommittedStore(t *testing.T) {
	result := generateStore(t)
	require.Equal(t, 6, result.QueryCount)

	generated := make(map[string]string, len(result.Files))
	for _, file := range result.Files {
		require.True(t, strings.HasPrefix(string(file.Content), generatedHeader), "%s lacks the Piko header", file.Name)
		generated[file.Name] = string(file.Content)
	}

	if *updateGenerated {
		require.NoError(t, os.RemoveAll(generatedDirectory))
		require.NoError(t, os.MkdirAll(generatedDirectory, 0o755))
		for name, content := range generated {
			require.NoError(t, os.WriteFile(filepath.Join(generatedDirectory, name), []byte(content), 0o644))
		}
		return
	}

	entries, err := os.ReadDir(generatedDirectory)
	require.NoError(t, err, "missing generated store; run with -update")
	committed := make([]string, 0, len(entries))
	for _, entry := range entries {
		committed = append(committed, entry.Name())
	}
	names := make([]string, 0, len(generated))
	for name := range generated {
		names = append(names, name)
	}
	slices.Sort(names)
	require.Equal(t, names, committed)

	for _, name := range names {
		content, err := os.ReadFile(filepath.Join(generatedDirectory, name))
		require.NoError(t, err)
		require.Equal(t, string(content), generated[name], "%s changed; run with -update and review", name)
	}
}

func TestGeneratedStoreUsesPikoVocabulary(t *testing.T) {
	result := generateStore(t)

	contents := make(map[string]string, len(result.Files))
	for _, file := range result.Files {
		contents[file.Name] = string(file.Content)
		require.NotContains(t, string(file.Content), "seagull", "%s mentions Seagull", file.Name)
		require.NotContains(t, string(file.Content), "sgl", "%s mentions sgl", file.Name)
	}
	require.Contains(t, contents, "otel.go")
	require.Contains(t, contents["otel.go"], "func QueryNameResolver")
	require.Contains(t, contents["models.go"], `"piko.sh/piko/wdk/maths"`)
}
